// concRuns is how often the harness repeats a call the model found
// deadlocking or leaking: Go's scheduler cannot be told to take the model's
// interleaving, so a schedule-dependent one shows up only by repetition.
const concRuns = 200

// Harness renders the Go test file for one counterexample.
func Harness(pkgName string, t *contract.Target, p *contract.Property, cx *contract.Counterexample, abi *contract.ABI) (string, error) {
	fn, imports, err := HarnessFunc(t, p, cx, abi)
	if err != nil {
		return "", err
	}
	return File(pkgName, imports, []string{fn}), nil
}

// File wraps test functions in a file with the package clause and imports.
func File(pkgName string, imports []string, funcs []string) string {
	var b strings.Builder
	_ = fileTmpl.Execute(&b, struct {
		Package string
		Imports []string
		Funcs   []string
	}{pkgName, imports, funcs})
	return b.String()
}

// HarnessFunc renders the test function for a counterexample and the import
// paths it needs beyond encoding/json, fmt and testing.
func HarnessFunc(t *contract.Target, p *contract.Property, cx *contract.Counterexample, abi *contract.ABI) (string, []string, error) {
	return harnessFunc(t, p, cx, abi, false)
}

// ReplayHarnessFunc is HarnessFunc for a deadlock or leak the model found,
// replaying the model's schedule (cx.Schedule) in a package rewritten by
// internal/replay.
func ReplayHarnessFunc(t *contract.Target, p *contract.Property, cx *contract.Counterexample, abi *contract.ABI) (string, []string, error) {
	return harnessFunc(t, p, cx, abi, true)
}

// replayRuns: a replay is close to deterministic; the runs cover a select
// among ready cases the model did not force and the release at the end.
const replayRuns = 20

// raceRuns: runs of a data race's harness under -race.
const raceRuns = 20

// scheduleLit is the schedule as a Go literal of the controller's type. A
// step of a package other than pkg, which the replay does not rewrite, is
// external: the controller lets it through without a gate.
func scheduleLit(sched []contract.SchedStep, pkg string) string {
	var b strings.Builder
	b.WriteString("[]go2leanStep{")
	for i, st := range sched {
		if i > 0 {
			b.WriteString(", ")
		}
		ps := make([]string, len(st.Partners))
		for k, p := range st.Partners {
			ps[k] = strconv.Itoa(p)
		}
		fmt.Fprintf(&b, "{%d, %q, []int{%s}, %t}", st.G, st.Op, strings.Join(ps, ", "), st.Pkg != "" && st.Pkg != pkg)
	}
	b.WriteString("}")
	return b.String()
}

func harnessFunc(t *contract.Target, p *contract.Property, cx *contract.Counterexample, abi *contract.ABI, replay bool) (string, []string, error) {
	pkgName := ""
	d := harnessData{Package: pkgName, ID: cx.ID, Func: t.Func}
	imports := map[string]bool{}
	for i, r := range abi.Results {
		name := "ret"
		if len(abi.Results) > 1 {
			name = fmt.Sprintf("ret%d", i)
		}
		if r.GoType == "" {
			return "", nil, fmt.Errorf("result %d has no Go type", i)
		}
		d.Rets = append(d.Rets, name)
		d.RetTypes = append(d.RetTypes, r.GoType)
		if r.Func {
			d.RetPrint = append(d.RetPrint, name+" != nil")
		} else {
			d.RetPrint = append(d.RetPrint, name)
		}
		if r.TypePkg != "" {
			imports[r.TypePkg] = true
		}
		for _, ip := range r.ExtraPkgs {
			imports[ip] = true
		}
	}
	for _, ty := range abi.Types {
		for _, f := range ty.Fields {
			collectImports(f, imports)
		}
	}
	var names []string
	used := map[string]bool{}
	for i, prm := range abi.Params {
		decl, err := paramDecl(abi, prm, cx)
		if err != nil {
			return "", nil, err
		}
		// The variable takes the parameter's name unless that is blank,
		// repeated, or would shadow a package the test uses.
		name := prm.Go
		if name == "_" || name == "" || used[name] || reservedName[name] || shadowsImport(abi, name, imports) {
			name = fmt.Sprintf("go2leanP%d", i)
		}
		used[name] = true
		if name != prm.Go {
			decl = strings.Replace(decl, prm.Go, name, 1)
		}
		d.Decls = append(d.Decls, decl)
		names = append(names, name)
		collectImports(prm, imports)
		if prm.Kind == contract.ABIError && cx.Inputs[prm.Model[0]] != "nil" {
			imports["errors"] = true
		}
		if needsErrors(abi, prm, cx.Objects[prm.Go]) {
			imports["errors"] = true
		}
	}
	// Floats are written as math.Float64frombits(bits) (kept only if used).
	imports["math"] = true
	// Types in the table may be reached only through references; their
	// imports join the candidates, which are kept only when the generated
	// code names the package.
	for _, t := range abi.Types {
		if t.TypePkg != "" {
			imports[t.TypePkg] = true
		}
		for _, f := range t.Fields {
			collectImports(f, imports)
		}
	}
	// A nil pointer or an empty literal may leave a type package unused, and
	// an unused import does not compile: keep only the packages whose
	// qualifier the generated declarations mention.
	decls := strings.Join(d.Decls, "\n") + "\n" + strings.Join(d.RetTypes, " ")
	for ip := range imports {
		if fixedImports[ip] {
			continue
		}
		name := importName(abi, ip)
		if usesPackage(decls, name) {
			if name != path.Base(ip) {
				d.Imports = append(d.Imports, fmt.Sprintf("%s %q", name, ip))
			} else {
				d.Imports = append(d.Imports, fmt.Sprintf("%q", ip))
			}
		}
	}
	sort.Strings(d.Imports)
	specNames := append([]string{}, names...) // the spec takes the slice itself
	if abi.Variadic && len(names) > 0 {
		names[len(names)-1] += "..."
	}
	d.Args = strings.Join(names, ", ")
	if abi.Method != "" && len(names) > 0 {
		// Methods: the receiver is the first parameter.
		d.Func = names[0] + "." + abi.Method
		d.Args = strings.Join(names[1:], ", ")
	}
	if c := abi.Ctor; c != nil && len(names) >= c.N {
		// The receiver comes from the package's constructor; an error from
		// it means the inputs were not valid for it (a false precondition).
		ctorArgs := strings.Join(names[:c.N], ", ")
		if c.Err {
			d.Setup = []string{
				fmt.Sprintf("go2leanRecv, go2leanErr := %s(%s)", c.Func, ctorArgs),
				`if go2leanErr != nil { go2leanRes["pre"] = false; return }`,
			}
		} else {
			d.Setup = []string{fmt.Sprintf("go2leanRecv := %s(%s)", c.Func, ctorArgs)}
		}
		d.Func = "go2leanRecv." + c.Method
		d.Args = strings.Join(names[c.N:], ", ")
	}
	if p.Precondition != nil {
		d.Pre = p.Precondition.Go
	}
	if p.Spec != nil {
		specArgs := append(append([]string{}, specNames...), d.Rets...)
		d.SpecCall = fmt.Sprintf("%s(%s)", p.Spec.GoFunc, strings.Join(specArgs, ", "))
	}
	if p.Kind == contract.KindNoHang {
		// A loop the model never leaves: one run under the watchdog, which
		// reports a call that has not returned after 2s (#86).
		d.Conc, d.ConcRuns, d.PkgPath, d.NoLeak = true, 1, t.Package, true
		d.Imports = append(d.Imports, `"runtime"`, `"strings"`, `"time"`)
	} else if m := modelPanic(cx); m == contract.PanicDeadlock || m == contract.PanicGoroutineLeak || m == contract.PanicDataRace || scheduleDependent(cx) {
		d.Conc, d.ConcRuns, d.PkgPath = true, concRuns, t.Package
		if m != contract.PanicDeadlock && m != contract.PanicGoroutineLeak && m != contract.PanicDataRace {
			// A panic or a false result under a concurrent schedule: Go's
			// scheduler takes the interleaving only now and then, so the
			// call is repeated until a run violates the property.
			d.NoLeak = true
			switch {
			case p.Kind == contract.KindSequence && len(d.Rets) == 1:
				d.Violated = "fmt.Sprint(" + d.Rets[0] + ") == \"false\""
			case d.SpecCall != "":
				d.Violated = "!" + d.SpecCall
			}
		}
		if m == contract.PanicDataRace {
			// Under -race: the detector sees unordered accesses whatever
			// the timing, so a few runs cover what the inputs reach.
			d.ConcRuns = raceRuns
		}
		if replay {
			d.Replay, d.ConcRuns = scheduleLit(cx.Schedule, t.Package), replayRuns
		}
		d.Imports = append(d.Imports, `"runtime"`, `"strings"`, `"time"`)
	}
	var b strings.Builder
	if err := harnessTmpl.Execute(&b, d); err != nil {
		return "", nil, err
	}
	return b.String(), d.Imports, nil
}

// paramDecl builds `name := <literal>` for one parameter from the
// counterexample's inputs and memory.
func paramDecl(abi *contract.ABI, p contract.ABIParam, cx *contract.Counterexample) (string, error) {
	switch p.Kind {
	case contract.ABIInt:
		v, ok := cx.Inputs[p.Model[0]]
		if !ok {
			return "", fmt.Errorf("counterexample has no value for %s", p.Go)
		}
		return fmt.Sprintf("%s := %s(%s)", p.Go, p.GoType, v), nil
	case contract.ABIFloat:
		v, ok := cx.Inputs[p.Model[0]]
		if !ok {
			return "", fmt.Errorf("counterexample has no value for %s", p.Go)
		}
		lit, err := floatLiteral(p, v)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s := %s", p.Go, lit), nil
	case contract.ABIBool:
		v, ok := cx.Inputs[p.Model[0]]
		if !ok {
			return "", fmt.Errorf("counterexample has no value for %s", p.Go)
		}
		return fmt.Sprintf("%s := %s", p.Go, v), nil
	case contract.ABIError:
		if cx.Inputs[p.Model[0]] == "nil" {
			return fmt.Sprintf("var %s error", p.Go), nil
		}
		return fmt.Sprintf("%s := errors.New(\"go2lean: opaque error\")", p.Go), nil
	case contract.ABIOpaque:
		// The model never looked inside: pass the zero value, except a
		// context, where nil would panic in callees the model havoc'd.
		if p.GoType == "context.Context" {
			return fmt.Sprintf("%s := context.Background()", p.Go), nil
		}
		if p.GoType == "*testing.T" {
			return fmt.Sprintf("%s := go2leanT", p.Go), nil
		}
		return fmt.Sprintf("var %s %s", p.Go, p.GoType), nil
	case contract.ABIString:
		if p.MaxLen < 0 {
			return fmt.Sprintf("var %s %s", p.Go, p.GoType), nil // an empty strings.Builder
		}
		raw, ok := cx.Objects[p.Go]
		if !ok {
			return "", fmt.Errorf("counterexample has no value for %s", p.Go)
		}
		var sv string
		if err := json.Unmarshal(raw, &sv); err != nil {
			return "", fmt.Errorf("string %s: %w", p.Go, err)
		}
		return fmt.Sprintf("%s := %s(%q)", p.Go, p.GoType, sv), nil
	case contract.ABIStruct, contract.ABIPtr, contract.ABIArray, contract.ABIMap, contract.ABIAny:
		raw, ok := cx.Objects[p.Go]
		if !ok {
			return "", fmt.Errorf("counterexample has no object for %s", p.Go)
		}
		var v any
		if err := json.Unmarshal(raw, &v); err != nil {
			return "", fmt.Errorf("object %s: %w", p.Go, err)
		}
		if p.Kind == contract.ABIPtr && v == nil {
			return fmt.Sprintf("var %s %s", p.Go, p.GoType), nil
		}
		expr, err := literal(abi, p, v)
		if err != nil {
			return "", err
		}
		if p.Kind == contract.ABIMap || p.Kind == contract.ABIAny {
			// Typed declaration: an interface holds the literal's own type.
			return fmt.Sprintf("var %s %s = %s", p.Go, p.GoType, expr), nil
		}
		return fmt.Sprintf("%s := %s", p.Go, expr), nil
	case contract.ABISlice:
		if p.ElemParam != nil {
			raw, ok := cx.Objects[p.Go]
			if !ok {
				return "", fmt.Errorf("counterexample has no object for %s", p.Go)
			}
			var v any
			if err := json.Unmarshal(raw, &v); err != nil {
				return "", fmt.Errorf("object %s: %w", p.Go, err)
			}
			expr, err := literal(abi, p, v)
			if err != nil {
				return "", err
			}
			c, _ := strconv.Atoi(cx.Inputs[p.Go+"_cap"])
			if elems, ok := v.([]any); ok && c > len(elems) {
				return fmt.Sprintf("%s := append(make(%s, 0, %d), %s...)", p.Go, p.GoType, c, expr), nil
			}
			return fmt.Sprintf("%s := %s", p.Go, expr), nil
		}
		n, err := strconv.Atoi(cx.Inputs[p.Go+"_len"])
		if err != nil {
			return "", fmt.Errorf("counterexample has no length for %s", p.Go)
		}
		c, err := strconv.Atoi(cx.Inputs[p.Go+"_cap"])
		if err != nil || c < n {
			c = n
		}
		elems := make([]string, n)
		mem := cx.Memory[p.Go]
		for i := range elems {
			elems[i] = "0"
			if i < len(mem) {
				elems[i] = mem[i]
			}
		}
		// go_hint "name[i]" havoc values (LLVM frontend) override memory.
		for _, h := range cx.Havoc {
			if h.GoHint == p.Go+"[i]" && h.Iter < n {
				elems[h.Iter] = h.Value
			}
		}
		if c == n {
			return fmt.Sprintf("%s := %s{%s}", p.Go, p.GoType, strings.Join(elems, ", ")), nil
		}
		return fmt.Sprintf("%s := append(make(%s, 0, %d), %s)", p.Go, p.GoType, c, strings.Join(elems, ", ")), nil
	}
	return "", fmt.Errorf("parameter %s: unsupported kind %s", p.Go, p.Kind)
}

// literal renders the Go expression for a value of the ABI type p: a struct
// is a JSON array of its fields in order, a pointer is null or its pointee.
func literal(abi *contract.ABI, p contract.ABIParam, v any) (string, error) {
	if p.TypeRef != "" {
		for _, t := range abi.Types {
			if t.GoType == p.TypeRef {
				p.Fields = t.Fields
			}
		}
	}
	if p.Kind == contract.ABIFloat {
		// Nested values are rendered signed by the model: back to the bits.
		if str, ok := v.(string); ok && strings.HasPrefix(str, "-") {
			if n, ok := new(big.Int).SetString(str, 10); ok {
				v = n.Add(n, new(big.Int).Lsh(big.NewInt(1), uint(p.Width))).String()
			}
		}
		return floatLiteral(p, v)
	}
	switch p.Kind {
	case contract.ABIInt:
		s, ok := v.(string)
		if !ok {
			return "", fmt.Errorf("%s: expected an integer string, got %v", p.Go, v)
		}
		// Nested values are rendered signed by the model; an unsigned field
		// gets its two's-complement reading back.
		if w, signed, ok := p.IntInfo(); ok && !signed && strings.HasPrefix(s, "-") {
			if n, ok := new(big.Int).SetString(s, 10); ok {
				s = n.Add(n, new(big.Int).Lsh(big.NewInt(1), uint(w))).String()
			}
		}
		return fmt.Sprintf("%s(%s)", p.GoType, s), nil
	case contract.ABIBool:
		return fmt.Sprint(v), nil
	case contract.ABIOpaque:
		if p.Zero != "" {
			return p.Zero, nil
		}
		return "nil", nil
	case contract.ABIString:
		if p.MaxLen < 0 {
			return p.GoType + "{}", nil // an empty strings.Builder
		}
		sv, _ := v.(string)
		return fmt.Sprintf("%s(%q)", p.GoType, sv), nil
	case contract.ABIError:
		if v == "nil" || v == nil {
			return "error(nil)", nil
		}
		return "errors.New(\"go2lean: opaque error\")", nil
	case contract.ABIStruct:
		fields, ok := v.([]any)
		if !ok || len(fields) != len(p.Fields) {
			return "", fmt.Errorf("%s: expected %d fields, got %v", p.Go, len(p.Fields), v)
		}
		if sdkResponse(abi, p) {
			// An SDK response value: such values only come from decoding
			// (raw JSON and member metadata included), and the generator
			// builds them so (sdkDoc), so decode the document. A struct of
			// the program that holds one is written as a literal: its own
			// unexported fields (maps a constructor made) must not be lost
			// to a decode.
			doc, err := json.Marshal(jsonDoc(abi, p, v))
			if err != nil {
				return "", err
			}
			return fmt.Sprintf("func() %[1]s { var go2leanV %[1]s; _ = json.Unmarshal([]byte(%[2]q), &go2leanV); return go2leanV }()", p.GoType, doc), nil
		}
		if !canImport(abi.Package, p.TypePkg) {
			return "", fmt.Errorf("%s: type %s lives in an internal package the test cannot import", p.Go, p.GoType)
		}
		var parts []string
		for i, f := range p.Fields {
			if f.JSONText {
				continue // empty here (a non-empty one is decoded above)
			}
			if f.Kind == contract.ABIOpaque {
				continue // zero value: nil map, nil interface, nil func
			}
			if isZeroJSON(abi, f, fields[i]) {
				// Omitted: the zero value needs no setting, and some zero
				// values cannot be spelled from the test at all (an
				// anonymous struct type with unexported fields).
				continue
			}
			if p.TypePkg != "" && !token.IsExported(f.Go) {
				if isZeroJSON(abi, f, fields[i]) {
					continue // the zero value needs no setting
				}
				return "", fmt.Errorf("%s: cannot set unexported field %s of %s from the test", p.Go, f.Go, p.GoType)
			}
			e, err := literal(abi, f, fields[i])
			if err != nil {
				return "", err
			}
			if emptyComposite(e) && f.Kind != contract.ABIMap && f.Kind != contract.ABIAny && !(f.Kind == contract.ABISlice && !strings.Contains(e, "struct{")) {
				// An empty composite literal is the zero value (an empty map
				// or slice is not: writes work, JSON encodes [] and {}; nor is
				// an interface holding one: it is not nil): leave it out
				// (an anonymous struct with a foreign unexported field, like
				// the SDKs' JSON metadata, cannot be spelled here at all).
				continue
			}
			parts = append(parts, f.Go+": "+e)
		}
		return p.GoType + "{" + strings.Join(parts, ", ") + "}", nil
	case contract.ABISlice, contract.ABIArray:
		if v == nil {
			return "(" + p.GoType + ")(nil)", nil
		}
		elems, ok := v.([]any)
		if !ok {
			return "", fmt.Errorf("%s: expected a JSON array, got %v", p.Go, v)
		}
		var parts []string
		for _, e := range elems {
			s, err := literal(abi, p.ElemAsParam(), e)
			if err != nil {
				return "", err
			}
			parts = append(parts, s)
		}
		return p.GoType + "{" + strings.Join(parts, ", ") + "}", nil
	case contract.ABIMap:
		if v == nil {
			return "(" + p.GoType + ")(nil)", nil
		}
		obj, _ := v.(map[string]any)
		entries, ok := obj["map"].([]any)
		if !ok {
			return "", fmt.Errorf("%s: expected {\"map\": [...]}, got %v", p.Go, v)
		}
		var parts []string
		for _, e := range entries {
			kv, ok := e.([]any)
			if !ok || len(kv) != 2 {
				return "", fmt.Errorf("%s: bad map entry %v", p.Go, e)
			}
			k, err := literal(abi, *p.Key, kv[0])
			if err != nil {
				return "", err
			}
			val, err := literal(abi, *p.Value, kv[1])
			if err != nil {
				return "", err
			}
			parts = append(parts, k+": "+val)
		}
		return p.GoType + "{" + strings.Join(parts, ", ") + "}", nil
	case contract.ABIAny:
		if v == nil {
			return "nil", nil
		}
		obj, _ := v.(map[string]any)
		tag, _ := obj["tag"].(float64)
		for _, a := range p.Alts {
			if float64(a.Tag) == tag {
				lit, err := literal(abi, a, obj["v"])
				if err != nil {
					return "", err
				}
				// An untyped constant takes its default type in an
				// interface: int64(5), not 5, for an int64 alternative.
				switch {
				case a.Kind == contract.ABIInt && a.GoType != "int",
					a.Kind == contract.ABIString && a.GoType != "string",
					a.Kind == contract.ABIBool && a.GoType != "bool":
					if !strings.HasPrefix(lit, a.GoType+"(") {
						lit = a.GoType + "(" + lit + ")"
					}
				}
				return lit, nil
			}
		}
		return "", fmt.Errorf("%s: no alternative with type tag %v", p.Go, obj["tag"])
	case contract.ABIPtr:
		if v == nil {
			return "(" + p.GoType + ")(nil)", nil
		}
		if p.Pointee.Kind == contract.ABIOpaque || v == "opaque" {
			// A pointer to a value the model never looked into (or to a nil
			// map or interface): a pointer to its zero value.
			return "new(" + p.Pointee.GoType + ")", nil
		}
		inner, err := literal(abi, *p.Pointee, v)
		if err != nil {
			return "", err
		}
		if (p.Pointee.Kind == contract.ABIStruct && !strings.HasPrefix(inner, "func()")) || p.Pointee.MaxLen < 0 {
			return "&" + inner, nil
		}
		// A pointer to a scalar: allocate it in a closure.
		return fmt.Sprintf("func() %s { v := %s; return &v }()", p.GoType, inner), nil
	}
	return "", fmt.Errorf("%s: cannot render kind %s", p.Go, p.Kind)
}

// withTable fills in the fields of a type-table reference.
func withTable(abi *contract.ABI, p contract.ABIParam) contract.ABIParam {
	if p.TypeRef != "" {
		for _, t := range abi.Types {
			if t.GoType == p.TypeRef {
				p.Fields = t.Fields
			}
		}
	}
	return p
}

// sdkResponse says whether p is an SDK response type: one the frontend gave
// a JSON description, or (an ABI without one) a struct whose JSON field
// holds the raw JSON text (respjson metadata).
func sdkResponse(abi *contract.ABI, p contract.ABIParam) bool {
	for _, t := range abi.Types {
		if t.GoType == p.TypeRef && p.TypeRef != "" && t.JSONDesc > 0 {
			return true
		}
	}
	for _, f := range withTable(abi, p).Fields {
		if f.Go == "JSON" && f.Kind == contract.ABIStruct {
			for _, g := range f.Fields {
				if g.JSONText {
					return true
				}
			}
		}
	}
	return false
}

// hasRawJSON says whether the value holds a non-empty generated raw JSON
// (an SDK response type's RawJSON()) anywhere.
func hasRawJSON(abi *contract.ABI, p contract.ABIParam, v any) bool {
	p = withTable(abi, p)
	switch p.Kind {
	case contract.ABIString:
		s, _ := v.(string)
		return p.JSONText && s != ""
	case contract.ABIStruct:
		fields, _ := v.([]any)
		for i, f := range p.Fields {
			if i < len(fields) && hasRawJSON(abi, f, fields[i]) {
				return true
			}
		}
	case contract.ABIPtr:
		return v != nil && v != "opaque" && p.Pointee != nil && hasRawJSON(abi, *p.Pointee, v)
	case contract.ABISlice, contract.ABIArray:
		elems, _ := v.([]any)
		for _, e := range elems {
			if hasRawJSON(abi, p.ElemAsParam(), e) {
				return true
			}
		}
	}
	return false
}

// jsonDoc is the JSON document an SDK response value with the model's
// contents decodes from: typed fields under their JSON names (zero ones
// left out), and each level's generated raw JSON members merged into its
// object where no typed field has the key.
func jsonDoc(abi *contract.ABI, p contract.ABIParam, v any) any {
	p = withTable(abi, p)
	if p.Kind == contract.ABIFloat {
		// The number json.Marshal writes for the float (NaN and infinities
		// have none: left out).
		str, _ := v.(string)
		n, ok := new(big.Int).SetString(str, 10)
		if !ok {
			return nil
		}
		if n.Sign() < 0 {
			n.Add(n, new(big.Int).Lsh(big.NewInt(1), uint(p.Width)))
		}
		f := math.Float64frombits(n.Uint64())
		if p.Width == 32 {
			f = float64(math.Float32frombits(uint32(n.Uint64())))
		}
		if math.IsNaN(f) || math.IsInf(f, 0) {
			return nil
		}
		return json.Number(strconv.FormatFloat(f, 'g', -1, p.Width))
	}
	switch p.Kind {
	case contract.ABIInt:
		s, _ := v.(string)
		if w, signed, ok := p.IntInfo(); ok && !signed && strings.HasPrefix(s, "-") {
			if n, ok := new(big.Int).SetString(s, 10); ok {
				s = n.Add(n, new(big.Int).Lsh(big.NewInt(1), uint(w))).String()
			}
		}
		return json.Number(s)
	case contract.ABIBool:
		return v == "true" || v == true
	case contract.ABIString:
		return v
	case contract.ABIStruct:
		fields, _ := v.([]any)
		obj := map[string]any{}
		var extra map[string]json.RawMessage
		var inlined any // a union's live scalar variant
		for i, f := range p.Fields {
			if i >= len(fields) {
				break
			}
			if f.Go == "JSON" && f.Kind == contract.ABIStruct {
				for j, g := range f.Fields {
					if s, ok := elemAt(fields[i], j).(string); g.JSONText && ok && s != "" {
						_ = json.Unmarshal([]byte(s), &extra)
					}
				}
				continue
			}
			if !token.IsExported(f.Go) || f.JSONName == "-" || f.Kind == contract.ABIOpaque || isZeroJSON(abi, f, fields[i]) {
				continue
			}
			d := jsonDoc(abi, f, fields[i])
			if f.JSONInline {
				if m, ok := d.(map[string]any); ok {
					for k, x := range m {
						obj[k] = x
					}
				} else {
					inlined = d
				}
				continue
			}
			obj[f.JSONName] = d
		}
		if inlined != nil && len(obj) == 0 {
			return inlined
		}
		for k, x := range extra {
			if _, typed := obj[k]; !typed {
				obj[k] = x
			}
		}
		return obj
	case contract.ABIPtr:
		if v == nil || v == "opaque" || p.Pointee == nil {
			return nil
		}
		return jsonDoc(abi, *p.Pointee, v)
	case contract.ABISlice, contract.ABIArray:
		elems, _ := v.([]any)
		if p.Kind == contract.ABISlice && strings.HasSuffix(p.GoType, "json.RawMessage") {
			// Raw JSON text: in the document as itself when it is JSON
			// (null otherwise), as the model writes it (GoSSA.jDoc).
			var b []byte
			for _, e := range elems {
				n, _ := strconv.Atoi(fmt.Sprint(e))
				b = append(b, byte(n))
			}
			if v == nil || !json.Valid(b) {
				return nil
			}
			return json.RawMessage(b)
		}
		out := []any{}
		for _, e := range elems {
			out = append(out, jsonDoc(abi, p.ElemAsParam(), e))
		}
		return out
	case contract.ABIMap:
		obj, _ := v.(map[string]any)
		entries, _ := obj["map"].([]any)
		out := map[string]any{}
		for _, e := range entries {
			if kv, ok := e.([]any); ok && len(kv) == 2 {
				out[fmt.Sprint(kv[0])] = jsonDoc(abi, *p.Value, kv[1])
			}
		}
		return out
	case contract.ABIAny:
		obj, _ := v.(map[string]any)
		for _, a := range p.Alts {
			if t, _ := obj["tag"].(float64); float64(a.Tag) == t {
				return jsonDoc(abi, a, obj["v"])
			}
		}
	}
	return nil
}

func elemAt(v any, i int) any {
	if xs, ok := v.([]any); ok && i < len(xs) {
		return xs[i]
	}
	return nil
}

// canImport applies Go's internal-package rule: a package under
// `<root>/internal/` is importable only from within `<root>`. Without the
// importing package (older ABI records) an internal path is refused.
func canImport(from, pkg string) bool {
	idx := strings.Index(pkg, "/internal/")
	root := ""
	switch {
	case idx >= 0:
		root = pkg[:idx]
	case strings.HasPrefix(pkg, "internal/"):
		root = ""
	case pkg == "internal" || strings.HasSuffix(pkg, "/internal"):
		root = strings.TrimSuffix(strings.TrimSuffix(pkg, "internal"), "/")
	default:
		return true
	}
	if from == "" {
		return false
	}
	return from == root || strings.HasPrefix(from, root+"/")
}

// fixedImports are in every harness file; reservedName lists the
// identifiers a parameter must not take in it.
var (
	fixedImports = map[string]bool{"encoding/json": true, "fmt": true, "testing": true}
	reservedName = map[string]bool{"json": true, "fmt": true, "testing": true, "errors": true}
)

// shadowsImport says whether a variable of this name would hide a package
// the test may import (a parameter named `oauth` next to an `oauth` type).
func shadowsImport(abi *contract.ABI, name string, imports map[string]bool) bool {
	for ip := range imports {
		if importName(abi, ip) == name {
			return true
		}
	}
	return false
}

// importName is the package name of an import path: recorded by the
// frontend when it differs from the path's last element.
func importName(abi *contract.ABI, ip string) string {
	if n, ok := abi.Imports[ip]; ok {
		return n
	}
	return path.Base(ip)
}

// usesPackage says whether the generated code refers to the package by
// its qualifier: `io.Reader`, not the "io." inside a string literal or
// inside another identifier (`ratio.`).
func usesPackage(code, qualifier string) bool {
	return packageRef(qualifier).MatchString(stripStrings(code))
}

func packageRef(qualifier string) *regexp.Regexp {
	return regexp.MustCompile(`(^|[^\w.])` + regexp.QuoteMeta(qualifier) + `\.`)
}

// stripStrings blanks the contents of Go string literals (with escapes).
func stripStrings(code string) string {
	var b strings.Builder
	inStr := false
	for i := 0; i < len(code); i++ {
		c := code[i]
		switch {
		case inStr && c == '\\':
			i++ // skip the escaped byte
		case c == '"':
			inStr = !inStr
			b.WriteByte(c)
		case inStr:
		default:
			b.WriteByte(c)
		}
	}
	return b.String()
}

// isZeroJSON says whether the model's value is the Go zero value of p.
func isZeroJSON(abi *contract.ABI, p contract.ABIParam, v any) bool {
	if p.TypeRef != "" {
		for _, t := range abi.Types {
			if t.GoType == p.TypeRef {
				p.Fields = t.Fields
			}
		}
	}
	switch p.Kind {
	case contract.ABIInt, contract.ABIFloat:
		// A float only at +0 (bits 0): leaving out a -0 would decode as +0.
		return v == "0"
	case contract.ABIBool:
		return v == "false" || v == false
	case contract.ABIString:
		return v == ""
	case contract.ABIError:
		return v == "nil" || v == nil
	case contract.ABIOpaque, contract.ABIPtr, contract.ABISlice, contract.ABIMap, contract.ABIAny:
		return v == nil
	case contract.ABIStruct, contract.ABIArray:
		elems, _ := v.([]any)
		for i, e := range elems {
			f := p.ElemAsParam()
			if p.Kind == contract.ABIStruct {
				if i >= len(p.Fields) {
					return false
				}
				f = p.Fields[i]
			}
			if !isZeroJSON(abi, f, e) {
				return false
			}
		}
		return true
	}
	return false
}

func collectImports(p contract.ABIParam, into map[string]bool) {
	for _, ip := range append([]string{p.TypePkg, p.ElemPkg}, p.ExtraPkgs...) {
		if ip != "" {
			into[ip] = true
		}
	}
	for _, f := range p.Fields {
		collectImports(f, into)
	}
	if p.Pointee != nil {
		collectImports(*p.Pointee, into)
	}
	if p.ElemParam != nil {
		collectImports(*p.ElemParam, into)
	}
	for _, q := range []*contract.ABIParam{p.Key, p.Value} {
		if q != nil {
			collectImports(*q, into)
		}
	}
	for _, a := range p.Alts {
		collectImports(a, into)
	}
}

// needsErrors reports whether rendering the object needs the errors package
// (a non-nil error somewhere inside a struct or pointee).
func needsErrors(abi *contract.ABI, p contract.ABIParam, raw json.RawMessage) bool {
	if raw == nil {
		return false
	}
	var v any
	if json.Unmarshal(raw, &v) != nil {
		return false
	}
	var walk func(p contract.ABIParam, v any) bool
	walk = func(p contract.ABIParam, v any) bool {
		if p.TypeRef != "" {
			for _, t := range abi.Types {
				if t.GoType == p.TypeRef {
					p.Fields = t.Fields
				}
			}
		}
		switch p.Kind {
		case contract.ABIError:
			return v != nil && v != "nil"
		case contract.ABIStruct:
			fields, _ := v.([]any)
			for i, f := range p.Fields {
				if i < len(fields) && walk(f, fields[i]) {
					return true
				}
			}
		case contract.ABIPtr:
			return v != nil && p.Pointee != nil && walk(*p.Pointee, v)
		case contract.ABISlice, contract.ABIArray:
			elems, _ := v.([]any)
			for _, e := range elems {
				if p.ElemParam != nil && walk(*p.ElemParam, e) {
					return true
				}
			}
		case contract.ABIMap:
			obj, _ := v.(map[string]any)
			entries, _ := obj["map"].([]any)
			for _, e := range entries {
				if kv, ok := e.([]any); ok && len(kv) == 2 && walk(*p.Value, kv[1]) {
					return true
				}
			}
		}
		return false
	}
	return walk(p, v)
}

// emptyComposite says whether e is a composite literal with no elements:
// T{} where T may itself contain braces (struct{A int}{}).
func emptyComposite(e string) bool {
	if !strings.HasSuffix(e, "{}") {
		return false
	}
	typ := strings.TrimSuffix(e, "{}")
	depth := 0
	for _, r := range typ {
		switch r {
		case '{':
			depth++
		case '}':
			depth--
		}
		if depth < 0 {
			return false
		}
	}
	return depth == 0
}

// floatLiteral is a float of the model as Go code: its exact bits,
// math.Float64frombits(0x...) (or Float32frombits), converted to the
// parameter's type (#148).
func floatLiteral(p contract.ABIParam, v any) (string, error) {
	s, ok := v.(string)
	if !ok {
		return "", fmt.Errorf("%s: expected the bits of a float, got %v", p.Go, v)
	}
	bits, err := strconv.ParseUint(s, 10, 64)
	if err != nil {
		return "", fmt.Errorf("%s: float bits %q: %w", p.Go, s, err)
	}
	if p.Width == 32 {
		return fmt.Sprintf("%s(math.Float32frombits(0x%08x))", p.GoType, bits), nil
	}
	return fmt.Sprintf("%s(math.Float64frombits(0x%016x))", p.GoType, bits), nil
}
