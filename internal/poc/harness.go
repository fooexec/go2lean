// Package poc is M3: it realises a Counterexample as a real Go test, runs it
// with the Go toolchain and judges whether the model's violation reproduces.
// It is the only source of trust in the pipeline: every reported bug carries
// a verdict from here.
package poc

import (
	"encoding/json"
	"fmt"
	"go/token"
	"math"
	"math/big"
	"path"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"text/template"

	"github.com/andreasfoo/go2lean/internal/contract"
)

// harnessData feeds the test template.
type harnessData struct {
	Package  string
	Imports  []string // extra import paths for named parameter/result types
	ID       string
	Decls    []string // parameter declarations
	Args     string   // comma-separated parameter names
	Func     string
	Rets     []string // result variable names (ret, or ret0, ret1, ...); empty when none
	RetTypes []string
	// RetPrint is what the test prints for the results: a func value is
	// printed as its nil-ness (vet rejects printing a func).
	RetPrint []string
	Pre      string // Go expression or ""
	// Setup are statements run before the call inside the panic guard
	// (a constructor-built receiver).
	Setup    []string
	SpecCall string // e.g. SpecSum(xs, ret) or ""
	// Conc: the model found a deadlock or a goroutine leak. The call runs
	// in a goroutine under a watchdog, ConcRuns times, and after each the
	// test looks for goroutines of package PkgPath blocked for good.
	Conc     bool
	ConcRuns int
	PkgPath  string
	// Violated: for a panic or a false result the model found under a
	// concurrent schedule, a Go expression true when a run violated the
	// property; the runs stop there. Such a harness does not stop on a
	// leaked goroutine (NoLeak): the leak is not what the model found.
	Violated string
	NoLeak   bool
	// Replay: the model's schedule as a Go literal ([]go2leanStep{...}):
	// the package is rewritten (internal/replay) and each run follows it.
	Replay string
}

func (d harnessData) RetList() string { return strings.Join(d.Rets, ", ") }

// RetPrintList is the Sprint argument list for the results.
func (d harnessData) RetPrintList() string { return strings.Join(d.RetPrint, ", ") }

