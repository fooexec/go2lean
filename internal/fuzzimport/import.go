// Package fuzzimport reads a package's Go fuzz targets as go2lean specs:
// the function a `FuzzXxx` hands to `f.Fuzz` is a property of its inputs
// (it must not fail and not panic), so each becomes a sequence spec over
// the same parameters, searched by the model like any other spec. A
// project with fuzz targets gets go2lean's search without writing a spec.
//
// The translation is at the source level, so the model needs nothing new:
// the body is kept, and its uses of the *testing.T become plain code:
// t.Fatal, t.Fatalf and t.FailNow mark the run failed and return;
// t.Error, t.Errorf and t.Fail mark it failed and go on; t.Skip, t.Skipf
// and t.SkipNow end it as passed (vacuous); t.Log, t.Logf and t.Helper do
// nothing but evaluate their arguments. A target whose function uses t in
// any other way (passes it to a helper, calls t.Run, uses it in a nested
// function) or reads a variable of the FuzzXxx function around it is left
// out, with the reason. The generated file goes to the build through an
// overlay: nothing is written into the package.
package fuzzimport

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/printer"
	"go/token"
	"go/types"
	"maps"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/ast/astutil"
	"golang.org/x/tools/go/packages"
)

// FileName is the generated file, next to the package's own test files.
const FileName = "zz_go2lean_fuzzspecs_test.go"

// SpecPrefix starts the name of a spec made from fuzz target FuzzXxx:
// Go2LeanFuzz_FuzzXxx.
const SpecPrefix = "Go2LeanFuzz_"

// Skipped is a fuzz target that was not translated, and why.
type Skipped struct {
	Package string
	Fuzz    string
	Reason  string
}

// Specs loads the packages matching patterns (from dir) with their tests
// and returns the overlay of generated spec files (absolute path to
// contents), one per package with a fuzz target that translates.
func Specs(dir string, patterns ...string) (map[string][]byte, []Skipped, error) {
	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo,
		Dir: dir, Tests: true}
	pkgs, err := packages.Load(cfg, patterns...)
	if err != nil {
		return nil, nil, err
	}
	overlay := map[string][]byte{}
	var skipped []Skipped
	for _, p := range pkgs {
		// The internal test variant: the fuzz targets in package p's own
		// _test.go files (an external pkg_test package cannot share a file
		// with the package's specs).
		if !strings.HasSuffix(p.ID, ".test]") || strings.HasSuffix(p.Name, "_test") || len(p.Syntax) == 0 {
			continue
		}
		src, skip := translate(p)
		skipped = append(skipped, skip...)
		if src != nil {
			overlay[filepath.Join(filepath.Dir(p.GoFiles[0]), FileName)] = src
		}
	}
	return overlay, skipped, nil
}

func translate(p *packages.Package) ([]byte, []Skipped) {
	var skipped []Skipped
	var funcs []string
	imports := map[string]string{} // path -> local name
	for _, file := range p.Syntax {
		if !strings.HasSuffix(p.Fset.Position(file.Pos()).Filename, "_test.go") {
			continue
		}
		for _, d := range file.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv != nil || !strings.HasPrefix(fd.Name.Name, "Fuzz") || fd.Body == nil {
				continue
			}
			src, err := spec(p, fd, imports)
			if err != nil {
				skipped = append(skipped, Skipped{Package: p.PkgPath, Fuzz: fd.Name.Name, Reason: err.Error()})
				continue
			}
			funcs = append(funcs, src)
		}
	}
	if len(funcs) == 0 {
		return nil, skipped
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by go2lean (internal/fuzzimport) from the package's fuzz targets. DO NOT EDIT.\n\npackage %s\n\n", p.Name)
	if len(imports) > 0 {
		b.WriteString("import (\n")
		var paths []string
		for path := range imports {
			paths = append(paths, path)
		}
		sort.Strings(paths)
		for _, path := range paths {
			fmt.Fprintf(&b, "\t%s %q\n", imports[path], path)
		}
		b.WriteString(")\n\n")
	}
	b.WriteString("// go2leanSink evaluates the arguments of a t.Log or t.Error call.\nfunc go2leanSink(...interface{}) {}\n")
	for _, f := range funcs {
		b.WriteString("\n")
		b.WriteString(f)
	}
	return []byte(b.String()), skipped
}

// spec writes the sequence spec for fuzz target fd, adding the imports it
// needs to imports only when it is written: a target it rejects leaves no
// import behind, which Go would reject as unused.
func spec(p *packages.Package, fd *ast.FuncDecl, imports map[string]string) (string, error) {
	own := map[string]string{}
	src, err := specOwn(p, fd, own)
	if err == nil {
		maps.Copy(imports, own)
	}
	return src, err
}

func specOwn(p *packages.Package, fd *ast.FuncDecl, imports map[string]string) (string, error) {
	params := fd.Type.Params.List
	if len(params) != 1 || len(params[0].Names) != 1 {
		return "", fmt.Errorf("not a fuzz target (one *testing.F parameter)")
	}
	fObj := p.TypesInfo.Defs[params[0].Names[0]]
	// The f.Fuzz(func(t *testing.T, ...) { ... }) call.
	var lit *ast.FuncLit
	ast.Inspect(fd.Body, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok || len(call.Args) != 1 {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != "Fuzz" {
			return true
		}
		if id, ok := sel.X.(*ast.Ident); ok && p.TypesInfo.Uses[id] == fObj {
			lit, _ = call.Args[0].(*ast.FuncLit)
		}
		return true
	})
	if lit == nil {
		return "", fmt.Errorf("no f.Fuzz(func literal) call")
	}
	// Parameters: the *testing.T, then the fuzzed values.
	var tObj types.Object
	var names, decls []string
	n := 0
	for _, field := range lit.Type.Params.List {
		typ := p.TypesInfo.TypeOf(field.Type)
		for _, id := range field.Names {
			if n == 0 {
				tObj = p.TypesInfo.Defs[id]
				n++
				continue
			}
			name := id.Name
			if name == "_" {
				name = fmt.Sprintf("go2leanArg%d", n)
			}
			names = append(names, name)
			decls = append(decls, name+" "+types.TypeString(typ, qualifier(p.Types, imports)))
			n++
		}
	}
	if n < 2 {
		return "", fmt.Errorf("the fuzz function takes no input")
	}
	// The body must not read FuzzXxx's own variables, and may use t only
	// in calls of the methods above, as statements of its own body.
	var bad error
	ast.Inspect(lit.Body, func(nd ast.Node) bool {
		id, ok := nd.(*ast.Ident)
		if !ok || bad != nil {
			return bad == nil
		}
		obj := p.TypesInfo.Uses[id]
		if obj == nil {
			return true
		}
		if pn, ok := obj.(*types.PkgName); ok {
			imports[pn.Imported().Path()] = pn.Name()
			return true
		}
		if obj.Pos() >= fd.Pos() && obj.Pos() < fd.End() && !(obj.Pos() >= lit.Pos() && obj.Pos() < lit.End()) && obj != tObj {
			bad = fmt.Errorf("the fuzz function reads %s, a variable of %s", id.Name, fd.Name.Name)
		}
		return true
	})
	if bad != nil {
		return "", bad
	}
	body, err := rewrite(p, lit, tObj)
	if err != nil {
		return "", err
	}
	name := SpecPrefix + fd.Name.Name
	return fmt.Sprintf("// go2lean:sequence %s\n// %s is fuzz target %s as a spec: its function neither fails nor panics.\nfunc %s(%s) bool {\n\tgo2leanFailed, go2leanSkipped := false, false\n\tfunc() %s()\n\treturn go2leanSkipped || !go2leanFailed\n}\n",
		name, name, fd.Name.Name, name, strings.Join(decls, ", "), body), nil
}

func qualifier(pkg *types.Package, imports map[string]string) types.Qualifier {
	return func(p *types.Package) string {
		if p == pkg {
			return ""
		}
		imports[p.Path()] = p.Name()
		return p.Name()
	}
}

// rewrite prints the body of lit with its t calls replaced.
func rewrite(p *packages.Package, lit *ast.FuncLit, tObj types.Object) (string, error) {
	var bad error
	isT := func(e ast.Expr) bool {
		id, ok := e.(*ast.Ident)
		return ok && tObj != nil && p.TypesInfo.Uses[id] == tObj
	}
	// Uses of t outside a statement-level method call are not supported.
	allowed := map[*ast.Ident]bool{}
	for _, st := range lit.Body.List {
		ast.Inspect(st, func(nd ast.Node) bool {
			if _, ok := nd.(*ast.FuncLit); ok {
				return false // a nested function: its t uses stay disallowed
			}
			es, ok := nd.(*ast.ExprStmt)
			if !ok {
				return true
			}
			if call, ok := es.X.(*ast.CallExpr); ok {
				if sel, ok := call.Fun.(*ast.SelectorExpr); ok && isT(sel.X) {
					allowed[sel.X.(*ast.Ident)] = true
				}
			}
			return true
		})
	}
	ast.Inspect(lit.Body, func(nd ast.Node) bool {
		if id, ok := nd.(*ast.Ident); ok && isT(id) && !allowed[id] && bad == nil {
			bad = fmt.Errorf("the fuzz function uses t other than in a t.Fatal, t.Error, t.Skip or t.Log call")
		}
		return bad == nil
	})
	if bad != nil {
		return "", bad
	}
	body := astutil.Apply(lit.Body, func(c *astutil.Cursor) bool {
		if _, ok := c.Node().(*ast.FuncLit); ok {
			return false
		}
		es, ok := c.Node().(*ast.ExprStmt)
		if !ok {
			return true
		}
		call, ok := es.X.(*ast.CallExpr)
		if !ok {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || !isT(sel.X) {
			return true
		}
		sink := &ast.ExprStmt{X: &ast.CallExpr{Fun: ast.NewIdent("go2leanSink"), Args: call.Args, Ellipsis: call.Ellipsis}}
		set := func(v string) ast.Stmt {
			return &ast.AssignStmt{Lhs: []ast.Expr{ast.NewIdent(v)}, Tok: token.ASSIGN, Rhs: []ast.Expr{ast.NewIdent("true")}}
		}
		switch sel.Sel.Name {
		case "Fatal", "Fatalf", "FailNow":
			c.Replace(&ast.BlockStmt{List: []ast.Stmt{sink, set("go2leanFailed"), &ast.ReturnStmt{}}})
		case "Error", "Errorf", "Fail":
			c.Replace(&ast.BlockStmt{List: []ast.Stmt{sink, set("go2leanFailed")}})
		case "Skip", "Skipf", "SkipNow":
			c.Replace(&ast.BlockStmt{List: []ast.Stmt{sink, set("go2leanSkipped"), &ast.ReturnStmt{}}})
		case "Log", "Logf", "Helper":
			c.Replace(sink)
		default:
			bad = fmt.Errorf("the fuzz function calls t.%s", sel.Sel.Name)
		}
		return true
	}, nil)
	if bad != nil {
		return "", bad
	}
	var buf bytes.Buffer
	if err := printer.Fprint(&buf, p.Fset, body); err != nil {
		return "", err
	}
	return buf.String(), nil
}
