// Package geninst gives the package's generic functions a model: a
// generic function has none until something instantiates it, so for each
// exported one it writes a wrapper that calls it at simple type arguments
// (int, string, float64, bool: the first ones its constraints accept),
// into a test file the compile stage and the replay both take as an
// overlay. The wrapper is an ordinary target: Go2LeanGen_Map__int__string
// stands for Map[int, string].
package geninst

import (
	"fmt"
	"go/types"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"unicode"

	"golang.org/x/tools/go/packages"
)

// FileName is the overlay file the wrappers go in, in the package's
// directory.
const FileName = "zz_go2lean_generics_test.go"

// Prefix starts every wrapper's name; "__" separates the function's name
// from each type argument.
const Prefix = "Go2LeanGen_"

// candidates are the type arguments tried, in order.
var candidates = []string{"int", "string", "float64", "bool"}

// maxTries bounds the combinations tried for one function.
const maxTries = 64

// Display is how a wrapper's name reads in findings: Map[int, string].
// Any other name is returned as it is.
func Display(name string) string {
	rest, ok := strings.CutPrefix(name, Prefix)
	if !ok {
		return name
	}
	parts := strings.Split(rest, "__")
	if len(parts) < 2 {
		return rest
	}
	return parts[0] + "[" + strings.Join(parts[1:], ", ") + "]"
}

// Wrappers writes, for every package matching the patterns, the overlay
// file of its generic functions' wrappers, keyed by the file's path. It
// returns the functions each package's file instantiates.
func Wrappers(dir string, patterns ...string) (map[string][]byte, map[string][]string, error) {
	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedFiles | packages.NeedTypes | packages.NeedSyntax | packages.NeedTypesInfo,
		Dir: dir}
	pkgs, err := packages.Load(cfg, patterns...)
	if err != nil {
		return nil, nil, err
	}
	overlay := map[string][]byte{}
	done := map[string][]string{}
	for _, p := range pkgs {
		if p.Types == nil || len(p.GoFiles) == 0 || p.Name == "main" || len(p.Errors) > 0 {
			continue
		}
		src, names := file(p)
		if len(names) == 0 {
			continue
		}
		path := filepath.Join(filepath.Dir(p.GoFiles[0]), FileName)
		overlay[path] = src
		done[p.PkgPath] = names
	}
	return overlay, done, nil
}

// file writes the wrappers of package p's exported generic functions, and
// returns the functions it instantiates.
func file(p *packages.Package) ([]byte, []string) {
	imports := map[string]string{} // path -> local name
	names := map[string]bool{}     // local names taken
	qual := func(other *types.Package) string {
		if other == p.Types {
			return ""
		}
		if n, ok := imports[other.Path()]; ok {
			return n
		}
		n := other.Name()
		for i := 2; names[n] || p.Types.Scope().Lookup(n) != nil; i++ {
			n = fmt.Sprintf("%s%d", other.Name(), i)
		}
		names[n] = true
		imports[other.Path()] = n
		return n
	}
	scope := p.Types.Scope()
	var funcs, wrapped []string
	for _, name := range scope.Names() {
		fn, ok := scope.Lookup(name).(*types.Func)
		if !ok || !fn.Exported() || strings.HasPrefix(name, Prefix) {
			continue
		}
		sig := fn.Type().(*types.Signature)
		if sig.TypeParams().Len() == 0 {
			continue
		}
		if strings.HasSuffix(p.Fset.Position(fn.Pos()).Filename, "_test.go") {
			continue
		}
		// Imports are only kept for the wrappers written: a rejected one
		// would leave an unused import.
		saved := map[string]string{}
		for k, v := range imports {
			saved[k] = v
		}
		src, ok := wrapper(fn, sig, qual)
		if !ok {
			imports = saved
			continue
		}
		funcs = append(funcs, src)
		wrapped = append(wrapped, name)
	}
	if len(funcs) == 0 {
		return nil, nil
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by go2lean (internal/geninst) from the package's generic functions. DO NOT EDIT.\n\npackage %s\n\n", p.Name)
	if len(imports) > 0 {
		var paths []string
		for path := range imports {
			paths = append(paths, path)
		}
		sort.Strings(paths)
		b.WriteString("import (\n")
		for _, path := range paths {
			fmt.Fprintf(&b, "\t%s %q\n", imports[path], path)
		}
		b.WriteString(")\n")
	}
	for _, f := range funcs {
		b.WriteString("\n")
		b.WriteString(f)
	}
	return []byte(b.String()), wrapped
}

// foreignUnexported matches a qualified unexported name (pkg.name): a type
// the wrapper's package cannot spell.
var foreignUnexported = regexp.MustCompile(`\b[A-Za-z_]\w*\.[a-z_]\w*`)

// wrapper writes the wrapper of fn at the first type arguments its
// constraints accept, or false when none of the candidates fit or a
// parameter's type cannot be written in the package.
func wrapper(fn *types.Func, sig *types.Signature, qual types.Qualifier) (string, bool) {
	tps := sig.TypeParams()
	n := tps.Len()
	idx := make([]int, n)
	ctxt := types.NewContext()
	for try := 0; try < maxTries; try++ {
		targs := make([]types.Type, n)
		for i := range targs {
			targs[i] = types.Universe.Lookup(candidates[idx[i]]).Type()
		}
		if inst, err := types.Instantiate(ctxt, sig, targs, true); err == nil {
			return write(fn, inst.(*types.Signature), targs, qual)
		}
		// The next combination, the last parameter fastest.
		i := n - 1
		for i >= 0 {
			idx[i]++
			if idx[i] < len(candidates) {
				break
			}
			idx[i] = 0
			i--
		}
		if i < 0 {
			break
		}
	}
	return "", false
}

func write(fn *types.Func, sig *types.Signature, targs []types.Type, qual types.Qualifier) (string, bool) {
	var targNames, params, args []string
	for _, t := range targs {
		targNames = append(targNames, t.String())
	}
	for i := 0; i < sig.Params().Len(); i++ {
		t := sig.Params().At(i).Type()
		name := fmt.Sprintf("p%d", i)
		if sig.Variadic() && i == sig.Params().Len()-1 {
			s := types.TypeString(t.(*types.Slice).Elem(), qual)
			params = append(params, name+" ..."+s)
			args = append(args, name+"...")
			continue
		}
		params = append(params, name+" "+types.TypeString(t, qual))
		args = append(args, name)
	}
	var results []string
	for i := 0; i < sig.Results().Len(); i++ {
		results = append(results, types.TypeString(sig.Results().At(i).Type(), qual))
	}
	head := strings.Join(params, ", ") + strings.Join(results, ", ")
	if foreignUnexported.MatchString(head) {
		return "", false
	}
	res := ""
	switch len(results) {
	case 0:
	case 1:
		res = " " + results[0]
	default:
		res = " (" + strings.Join(results, ", ") + ")"
	}
	name := Prefix + fn.Name() + "__" + strings.Join(targNames, "__")
	for _, r := range name {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) && r != '_' {
			return "", false
		}
	}
	call := fmt.Sprintf("%s[%s](%s)", fn.Name(), strings.Join(targNames, ", "), strings.Join(args, ", "))
	body := "\t" + call + "\n"
	if len(results) > 0 {
		body = "\treturn " + call + "\n"
	}
	return fmt.Sprintf("// %s is %s[%s], for go2lean's search.\nfunc %s(%s)%s {\n%s}\n",
		name, fn.Name(), strings.Join(targNames, ", "), name, strings.Join(params, ", "), res, body), true
}
