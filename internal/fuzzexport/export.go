// Package fuzzexport writes go2lean specs as Go fuzz targets, so that
// `go test -fuzz` searches the same properties with the real code and
// coverage guidance (docs/eval/semver.md: on the same specs, Go's fuzzer
// found in seconds what the model could not reach).
//
// A postcondition spec becomes a target that calls the function (or the
// method) under test and then the spec on its arguments and results; a
// sequence spec is called as it is. Parameters of the types Go's fuzzer
// takes (strings, []byte, integers, floats, bools, and named types over
// them) are fuzz arguments; slices, arrays, structs and pointers to them
// are decoded from one more []byte argument, so every spec over such
// values can be fuzzed. A spec over other types (maps, interfaces, funcs,
// channels, another package's unexported fields) is skipped with the
// reason.
package fuzzexport

import (
	"fmt"
	"go/types"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"

	"github.com/fooexec/go2lean/internal/contract"
)

// Spec is one spec to export.
type Spec struct {
	Property string
	Kind     contract.PropertyKind // postcondition or sequence
	Spec     string                // the spec function
	Target   string                // the function or method under test ("T.M"); unused for a sequence
}

// Target is one exported fuzz target.
type Target struct {
	Property string
	Fuzz     string
}

// Skipped is a spec that could not be exported, and why.
type Skipped struct {
	Property string
	Reason   string
}

// FileName is the name of the generated test file in the package.
const FileName = "zz_go2lean_fuzz_test.go"

// Export loads the package (with its test files and the overlay, e.g. a
// spec file the package directory does not hold) and writes the fuzz
// targets for specs as the source of FileName.
func Export(root, pkgPath string, overlay map[string][]byte, specs []Spec) (string, []Target, []Skipped, error) {
	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedTypes | packages.NeedFiles, Dir: root, Tests: true, Overlay: overlay}
	pkgs, err := packages.Load(cfg, pkgPath)
	if err != nil {
		return "", nil, nil, err
	}
	// The internal test variant holds the package's _test.go files, where
	// specs live; the plain package when there are none.
	var pkg *packages.Package
	for _, p := range pkgs {
		if p.PkgPath == pkgPath && (pkg == nil || strings.HasSuffix(p.ID, ".test]")) {
			pkg = p
		}
	}
	if pkg == nil || pkg.Types == nil {
		return "", nil, nil, fmt.Errorf("fuzzexport: package %s not loaded", pkgPath)
	}
	g := &gen{pkg: pkg.Types, imports: map[string]string{}}
	var targets []Target
	var skipped []Skipped
	var bodies []string
	for _, s := range specs {
		body, err := g.target(s)
		if err != nil {
			skipped = append(skipped, Skipped{Property: s.Property, Reason: err.Error()})
			continue
		}
		bodies = append(bodies, body)
		targets = append(targets, Target{Property: s.Property, Fuzz: fuzzName(s.Spec)})
	}
	if len(targets) == 0 {
		return "", nil, skipped, nil
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by go2lean fuzz (internal/fuzzexport). DO NOT EDIT.\n\npackage %s\n\nimport (\n", pkg.Types.Name())
	b.WriteString("\tgo2leanBinary \"encoding/binary\"\n\tgo2leanMath \"math\"\n\t\"testing\"\n")
	var paths []string
	for p := range g.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%s %q\n", g.imports[p], p)
	}
	b.WriteString(")\n")
	b.WriteString(readerSrc)
	for _, body := range bodies {
		b.WriteString("\n")
		b.WriteString(body)
	}
	return b.String(), targets, skipped, nil
}

func fuzzName(spec string) string { return "FuzzGo2Lean_" + spec }

// readerSrc decodes structured values from the fuzzer's bytes: integers
// little-endian (zero past the end), lengths small, so every input is a
// value and short inputs reach the deep ones.
const readerSrc = `
var _ = go2leanMath.Float64frombits

// go2leanFuzzReader hands out the bytes of a fuzz input as values.
type go2leanFuzzReader struct{ b []byte }

func (r *go2leanFuzzReader) u8() uint8 {
	if len(r.b) == 0 {
		return 0
	}
	v := r.b[0]
	r.b = r.b[1:]
	return v
}

func (r *go2leanFuzzReader) u64() uint64 {
	var x [8]byte
	n := copy(x[:], r.b)
	r.b = r.b[n:]
	return go2leanBinary.LittleEndian.Uint64(x[:])
}

// n is a slice length: 0 to 8.
func (r *go2leanFuzzReader) n() int { return int(r.u8() % 9) }

// str is a string of up to 32 bytes.
func (r *go2leanFuzzReader) str() string {
	k := int(r.u8() % 33)
	if k > len(r.b) {
		k = len(r.b)
	}
	s := string(r.b[:k])
	r.b = r.b[k:]
	return s
}
`

type gen struct {
	pkg     *types.Package
	imports map[string]string // path -> alias
}

func (g *gen) qual(p *types.Package) string {
	if p == g.pkg {
		return ""
	}
	alias, ok := g.imports[p.Path()]
	if !ok {
		alias = fmt.Sprintf("go2leanI%d_%s", len(g.imports), p.Name())
		g.imports[p.Path()] = alias
	}
	return alias
}

func (g *gen) typeStr(t types.Type) string { return types.TypeString(t, g.qual) }

// fuzzArg is the fuzz argument type for a scalar t (its underlying basic
// type, or []byte), "" when t is not one.
func fuzzArg(t types.Type) string {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch u.Kind() {
		case types.Bool, types.String, types.Int, types.Int8, types.Int16, types.Int32, types.Int64,
			types.Uint, types.Uint8, types.Uint16, types.Uint32, types.Uint64, types.Float32, types.Float64:
			return u.Name()
		}
	case *types.Slice:
		if b, ok := u.Elem().Underlying().(*types.Basic); ok && b.Kind() == types.Uint8 {
			return "[]byte"
		}
	}
	return ""
}

// decode is an expression of type t built from the reader r, or an error
// naming the part that cannot be built.
func (g *gen) decode(t types.Type, depth int) (string, error) {
	if depth > 4 {
		return "", fmt.Errorf("type %s nests too deep", g.typeStr(t))
	}
	ts := g.typeStr(t)
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Kind() == types.Bool:
			return fmt.Sprintf("%s(r.u8()&1 == 1)", ts), nil
		case u.Kind() == types.String:
			return fmt.Sprintf("%s(r.str())", ts), nil
		case u.Info()&types.IsUnsigned != 0 && u.Kind() != types.Uintptr:
			return fmt.Sprintf("%s(r.u64())", ts), nil
		case u.Info()&types.IsInteger != 0:
			return fmt.Sprintf("%s(int64(r.u64()))", ts), nil
		case u.Kind() == types.Float64:
			return fmt.Sprintf("%s(go2leanMath.Float64frombits(r.u64()))", ts), nil
		case u.Kind() == types.Float32:
			return fmt.Sprintf("%s(go2leanMath.Float32frombits(uint32(r.u64())))", ts), nil
		}
	case *types.Slice:
		e, err := g.decode(u.Elem(), depth+1)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("func() %s { n := r.n(); s := make(%s, n); for i := range s { s[i] = %s }; return s }()", ts, ts, e), nil
	case *types.Array:
		e, err := g.decode(u.Elem(), depth+1)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("func() (a %s) { for i := range a { a[i] = %s }; return a }()", ts, e), nil
	case *types.Pointer:
		e, err := g.decode(u.Elem(), depth+1)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("func() %s { v := %s; return &v }()", ts, e), nil
	case *types.Struct:
		var fields []string
		for i := 0; i < u.NumFields(); i++ {
			f := u.Field(i)
			if !f.Exported() && f.Pkg() != g.pkg {
				return "", fmt.Errorf("type %s has an unexported field of another package (%s)", ts, f.Name())
			}
			if f.Name() == "_" {
				continue
			}
			e, err := g.decode(f.Type(), depth+1)
			if err != nil {
				return "", err
			}
			fields = append(fields, fmt.Sprintf("%s: %s", f.Name(), e))
		}
		return fmt.Sprintf("%s{%s}", ts, strings.Join(fields, ", ")), nil
	}
	return "", fmt.Errorf("parameter type %s cannot be built from fuzz input", ts)
}

// target writes the fuzz target for one spec.
func (g *gen) target(s Spec) (string, error) {
	specObj, ok := g.pkg.Scope().Lookup(s.Spec).(*types.Func)
	if !ok {
		return "", fmt.Errorf("spec function %s not in the package (is its file in the package directory?)", s.Spec)
	}
	ssig := specObj.Type().(*types.Signature)
	if r := ssig.Results(); r.Len() != 1 || !types.Identical(r.At(0).Type(), types.Typ[types.Bool]) {
		return "", fmt.Errorf("spec %s does not return a bool", s.Spec)
	}
	if ssig.Variadic() {
		return "", fmt.Errorf("spec %s is variadic", s.Spec)
	}
	// Inputs: the spec's parameters, or for a postcondition those the
	// target takes (receiver first); the rest are the target's results.
	nIn := ssig.Params().Len()
	var call func(args []string) string
	nRes := 0
	var resTypes []types.Type
	if s.Kind == contract.KindPostcondition {
		name := strings.SplitN(s.Target, "~", 2)[0]
		if strings.Contains(s.Target, "~") {
			return "", fmt.Errorf("target %s is built through a constructor (not exported yet)", s.Target)
		}
		var tsig *types.Signature
		if typ, method, ok := strings.Cut(name, "."); ok {
			tn, ok := g.pkg.Scope().Lookup(typ).(*types.TypeName)
			if !ok {
				return "", fmt.Errorf("receiver type %s not in the package", typ)
			}
			obj, _, _ := types.LookupFieldOrMethod(types.NewPointer(tn.Type()), true, g.pkg, method)
			m, ok := obj.(*types.Func)
			if !ok {
				return "", fmt.Errorf("method %s not found", name)
			}
			tsig = m.Type().(*types.Signature)
			nIn = tsig.Params().Len() + 1
			call = func(args []string) string {
				return fmt.Sprintf("%s.%s(%s)", args[0], method, strings.Join(spread(tsig, args[1:]), ", "))
			}
		} else {
			fn, ok := g.pkg.Scope().Lookup(name).(*types.Func)
			if !ok {
				return "", fmt.Errorf("target %s not in the package", name)
			}
			tsig = fn.Type().(*types.Signature)
			nIn = tsig.Params().Len()
			call = func(args []string) string { return fmt.Sprintf("%s(%s)", name, strings.Join(spread(tsig, args), ", ")) }
		}
		nRes = tsig.Results().Len()
		for i := 0; i < nRes; i++ {
			resTypes = append(resTypes, tsig.Results().At(i).Type())
		}
		if nIn+nRes != ssig.Params().Len() {
			return "", fmt.Errorf("spec %s takes %d parameters, the target %d and %d results", s.Spec, ssig.Params().Len(), nIn, nRes)
		}
	}
	var fuzzParams, setup, args []string
	usesData := false
	for i := 0; i < nIn; i++ {
		t := ssig.Params().At(i).Type()
		v := fmt.Sprintf("p%d", i)
		args = append(args, v)
		if a := fuzzArg(t); a != "" {
			fuzzParams = append(fuzzParams, fmt.Sprintf("a%d %s", i, a))
			setup = append(setup, fmt.Sprintf("%s := %s(a%d)", v, g.typeStr(t), i))
			continue
		}
		e, err := g.decode(t, 0)
		if err != nil {
			return "", err
		}
		usesData = true
		setup = append(setup, fmt.Sprintf("%s := %s", v, e))
	}
	if usesData {
		fuzzParams = append(fuzzParams, "go2leanData []byte")
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// %s checks property %s.\nfunc %s(f *testing.F) {\n\tf.Fuzz(func(t *testing.T, %s) {\n", fuzzName(s.Spec), s.Property, fuzzName(s.Spec), strings.Join(fuzzParams, ", "))
	if usesData {
		b.WriteString("\t\tr := &go2leanFuzzReader{b: go2leanData}\n")
	}
	for _, l := range setup {
		fmt.Fprintf(&b, "\t\t%s\n", l)
	}
	specArgs := args
	if s.Kind == contract.KindPostcondition {
		var rets []string
		for i := 0; i < nRes; i++ {
			rets = append(rets, fmt.Sprintf("r%d", i))
		}
		// A postcondition judges the runs that return: a panic of the
		// target is no_panic's to report (the input is skipped).
		for i, rt := range resTypes {
			fmt.Fprintf(&b, "\t\tvar r%d %s\n", i, g.typeStr(rt))
		}
		b.WriteString("\t\tfunc() {\n\t\t\tdefer func() {\n\t\t\t\tif recover() != nil {\n\t\t\t\t\tt.Skip(\"the target panicked\")\n\t\t\t\t}\n\t\t\t}()\n")
		if nRes > 0 {
			fmt.Fprintf(&b, "\t\t\t%s = %s\n", strings.Join(rets, ", "), call(args))
		} else {
			fmt.Fprintf(&b, "\t\t\t%s\n", call(args))
		}
		b.WriteString("\t\t}()\n")
		specArgs = append(append([]string{}, args...), rets...)
	}
	fmt.Fprintf(&b, "\t\tif !%s(%s) {\n\t\t\tt.Fatalf(\"go2lean: %s is false\")\n\t\t}\n\t})\n}\n", s.Spec, strings.Join(specArgs, ", "), s.Spec)
	return b.String(), nil
}

// spread passes a variadic target's last argument, a slice like the spec's
// parameter, as its variadic parameter.
func spread(sig *types.Signature, args []string) []string {
	if !sig.Variadic() || len(args) == 0 {
		return args
	}
	out := append([]string{}, args...)
	out[len(out)-1] += "..."
	return out
}
