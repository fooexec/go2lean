// Package prover turns a property that held on the exhaustive domain into a
// Lean theorem over all inputs, and asks Lean to prove it.
//
// It applies to functions whose parameters are all fixed-width integers or
// bools: the theorem quantifies over every BitVec value of each parameter,
// so it is a proof for the real input space, not a sample. The statement is
// about the model: the run returns without panicking (and, for a
// postcondition, the spec returns true), reads no havoc value and takes no
// under-approximation (docs/limitations.md §2), within the fuel bound.
//
// The proof unfolds the model with simp (the interpreter, the functions
// involved, the integer lemmas of Go2Lean.Proof.Simp and the core's array
// lemmas for the environment), splits on the branches, substitutes the run
// states and closes what is left with simp_all, then bv_decide. The trust
// base is read from `#print axioms`: a proof that needed bv_decide depends
// on Lean.ofReduceBool, so it trusts the compiler as well as the kernel.
package prover

import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
	"syscall"
	"time"

	"github.com/fooexec/go2lean/internal/contract"
)

// Trust bases of a proof.
const (
	TrustKernel   = "kernel"   // only the kernel and the standard axioms
	TrustCompiler = "compiler" // also Lean.ofReduceBool (bv_decide's LRAT check)
)

// Result of an attempt.
type Result struct {
	Proved bool
	Trust  string
	File   string // the theorem file, relative to the workspace lean dir
	Error  string // first error line when not proved
	Time   time.Duration
}

// Eligible says whether the prover applies to the ABI: every parameter one
// integer or bool model value.
func Eligible(abi *contract.ABI) bool {
	if len(abi.Params) == 0 || abi.Method != "" || abi.Ctor != nil || abi.Variadic {
		return false
	}
	for _, p := range abi.Params {
		if (p.Kind != contract.ABIInt && p.Kind != contract.ABIBool) || len(p.Model) != 1 {
			return false
		}
		if p.Kind == contract.ABIInt && p.Width == 0 {
			return false
		}
	}
	return true
}

// Fuel bounds the run inside the theorem (blocks entered plus calls); a
// function that needs more is not proved.
const Fuel = 64

var ident = regexp.MustCompile(`[^A-Za-z0-9_]`)

// Theorem writes the theorem file for prop and returns its path relative
// to leanDir. fid and sid are the model ids of the target and the spec
// (-1 for no_panic); funcs are the model ids the run may enter.
func Theorem(leanDir string, report *contract.ModelReport, prop *contract.Property, abi *contract.ABI,
	fid, sid int, funcs []int) (string, error) {
	var params, args []string
	for i, p := range abi.Params {
		x := fmt.Sprintf("x%d", i)
		if p.Kind == contract.ABIBool {
			params = append(params, fmt.Sprintf("(%s : Bool)", x))
			args = append(args, fmt.Sprintf(".bool %s", x))
		} else {
			params = append(params, fmt.Sprintf("(%s : BitVec %d)", x, p.Width))
			args = append(args, fmt.Sprintf(".int %d %s", p.Width, x))
		}
	}
	var names []string
	for i := range abi.Params {
		names = append(names, fmt.Sprintf("x%d", i))
	}
	var b strings.Builder
	fmt.Fprintf(&b, `import Std.Tactic.BVDecide
import Go2Lean.Search
import Go2Lean.Proof.Simp
import %[1]s

/-! Generated by go2lean's prover for property %[2]s. -/

open Go2Lean Go2Lean.SSA Go2Lean.GoSSA
open %[1]s

set_option maxHeartbeats 0
set_option maxRecDepth 100000

namespace Go2Lean.Proofs.%[3]s

def or0 : Oracle := { mem := fun _ _ => 0#64 }
def h0 : Havoc Val := fun _ _ => .unit
def resOk : Res Val → Bool | .ok _ => true | _ => false
def resTrue : Res Val → Bool | .ok (.bool true) => true | _ => false
def results : Res Val → List Val | .ok (.tuple vs) => vs | .ok v => [v] | _ => []

`, report.LeanModule, prop.ID, ident.ReplaceAllString(prop.ID, "_"))
	var unfold []string
	for _, id := range funcs {
		fmt.Fprintf(&b, "theorem prog_f%[1]d : prog.funcs[%[1]d]? = some f%[1]d := rfl\n", id)
		unfold = append(unfold, fmt.Sprintf("prog_f%d", id), fmt.Sprintf("f%d", id))
	}
	argList := "[" + strings.Join(args, ", ") + "]"
	fmt.Fprintf(&b, "\n/-- %s -/\ndef holds %s : Bool :=\n", prop.NL, strings.Join(params, " "))
	fmt.Fprintf(&b, "  let r := run prog or0 h0 %d %s %d\n", fid, argList, Fuel)
	if sid < 0 {
		b.WriteString("  resOk r.1 && r.2.log.isEmpty && r.2.assumed.isEmpty\n")
	} else {
		fmt.Fprintf(&b, "  let s := runFunc prog or0 h0 false %d (%s ++ results r.1) r.2 %d\n", sid, argList, Fuel)
		b.WriteString("  resOk r.1 && resTrue s.1 && s.2.log.isEmpty && s.2.assumed.isEmpty\n")
	}
	lemmas := fmt.Sprintf(`holds, run, runFunc, runBlock, execInstrs, enter, bindParams, %s,
    Dialect.denote, Dialect.denoteH, GoSSA.denoteH_spec, Dialect.toBool, Dialect.assumption,
    GoSSA.assumption, denote,
    Array.getElem!_eq_getD, Array.getD_eq_getD_getElem?, Array.getElem?_setIfInBounds,
    Array.size_setIfInBounds, Array.getElem?_replicate, Array.size_replicate,
    resOk, resTrue, results`, strings.Join(unfold, ", "))
	fmt.Fprintf(&b, `
theorem holds_all %[1]s : holds %[2]s = true := by
  simp [%[3]s]
  all_goals (repeat' split)
  all_goals (try simp_all [%[3]s])
  all_goals (try (repeat (cases ‹_ ∧ _›)))
  all_goals (try subst_vars)
  all_goals (try simp_all [%[3]s])
  all_goals bv_decide

#print axioms holds_all

end Go2Lean.Proofs.%[4]s
`, strings.Join(params, " "), strings.Join(names, " "), lemmas, ident.ReplaceAllString(prop.ID, "_"))
	rel := filepath.Join("Proofs", ident.ReplaceAllString(prop.ID, "_")+".lean")
	path := filepath.Join(leanDir, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	return rel, os.WriteFile(path, []byte(b.String()), 0o644)
}

// Check runs Lean on the theorem file (from leanDir, the workspace's lake
// project) and reads the outcome.
func Check(leanDir, rel string, budget time.Duration) Result {
	start := time.Now()
	r := Result{File: rel}
	// The lemma library is not imported by the search driver; build it
	// once per workspace (searches run in parallel).
	if err := buildLemmas(leanDir); err != nil {
		r.Error = err.Error()
		return r
	}
	ctx, cancel := context.WithTimeout(context.Background(), budget)
	defer cancel()
	cmd := exec.CommandContext(ctx, "lake", "lean", rel)
	cmd.Dir = leanDir
	// Kill the whole process group on timeout: killing lake alone leaves
	// its lean child running, and the output pipe open until it ends.
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error { return syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL) }
	cmd.WaitDelay = 5 * time.Second
	out, err := cmd.CombinedOutput()
	r.Time = time.Since(start)
	text := string(out)
	switch {
	case ctx.Err() != nil:
		r.Error = fmt.Sprintf("timeout after %s", budget)
	case err != nil && !errors.Is(err, context.Canceled) && strings.Contains(text, "error"):
		r.Error = firstError(text)
	default:
		axioms := axiomLine(text)
		switch {
		case axioms == "" || strings.Contains(axioms, "sorryAx"):
			r.Error = "no proof: " + firstError(text)
		case strings.Contains(axioms, "ofReduceBool"):
			r.Proved, r.Trust = true, TrustCompiler
		default:
			r.Proved, r.Trust = true, TrustKernel
		}
	}
	return r
}

var (
	lemmasMu  sync.Mutex
	lemmasErr = map[string]error{}
)

func buildLemmas(leanDir string) error { return buildTrusted(leanDir, "") }

// BuildTrusted builds the proof library and the model module in the
// workspace's Lean project, before any text an agent wrote is read there.
func BuildTrusted(leanDir, module string) error { return buildTrusted(leanDir, module) }

// buildTrusted builds the proof library and, unless empty, the model
// module in the workspace's Lean project, once per process.
func buildTrusted(leanDir, module string) error {
	lemmasMu.Lock()
	defer lemmasMu.Unlock()
	key := leanDir + "\x00" + module
	if err, done := lemmasErr[key]; done {
		return err
	}
	var err error
	// From leanDir, not with -d: elan picks the toolchain from the
	// lean-toolchain file of the current directory (CI has no default).
	args := []string{"build", "Go2Lean.Proof.Simp", "Go2Lean.Proof.Tactic"}
	if module != "" {
		args = append(args, "+"+module)
	}
	cmd := exec.Command("lake", args...)
	cmd.Dir = leanDir
	if out, e := cmd.CombinedOutput(); e != nil {
		msg := firstError(string(out))
		if msg == "" {
			// lake did not run, or failed without an error line (not on
			// PATH, killed): say how.
			msg = e.Error()
		}
		err = fmt.Errorf("lake %s: %s", strings.Join(args, " "), msg)
	}
	lemmasErr[key] = err
	return err
}

// axiomLine is what `#print axioms holds_all` printed (the list may wrap
// over several lines), or "" when it did not run.
func axiomLine(s string) string {
	i := strings.Index(s, "holds_all' depends on axioms")
	if i < 0 {
		if strings.Contains(s, "holds_all' does not depend on any axioms") {
			return "none"
		}
		return ""
	}
	rest := s[i:]
	if j := strings.Index(rest, "]"); j >= 0 {
		rest = rest[:j+1]
	}
	return strings.Join(strings.Fields(rest), " ")
}

// firstError is the first line of s that reports an error, else its first
// line (a message stays on one line), at most 300 bytes.
func firstError(s string) string {
	first := ""
	for _, l := range strings.Split(s, "\n") {
		if first == "" && strings.TrimSpace(l) != "" {
			first = l
		}
		if strings.Contains(l, "error") {
			first = l
			break
		}
	}
	if len(first) > 300 {
		first = first[:300]
	}
	return strings.TrimSpace(first)
}

// Closure lists the model ids the run of the given functions may enter
// (their calls, transitively, within the package).
func Closure(report *contract.ModelReport, roots ...int) []int {
	byID := map[int]contract.ModelFunc{}
	for _, f := range report.Funcs {
		byID[f.ID] = f
	}
	seen := map[int]bool{}
	var out []int
	var walk func(int)
	walk = func(id int) {
		if id < 0 || seen[id] {
			return
		}
		seen[id] = true
		out = append(out, id)
		for _, c := range byID[id].Calls {
			walk(c)
		}
	}
	for _, r := range roots {
		walk(r)
	}
	return out
}
